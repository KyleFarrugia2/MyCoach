/**
 * Cross-platform parity fixture for the adaptive model.
 *
 * The TypeScript model (reference) and the Swift port must produce identical numbers. This file:
 *   - with GEN_FIXTURE=1: regenerates tests/fixtures/adaptive-fixture.json and
 *     ../MyCoachTests/AdaptiveModelFixture.swift (the same JSON embedded for XCTest);
 *   - otherwise: asserts the committed fixture still matches the current TypeScript implementation.
 *
 *   npm run fixtures     # after any change to src/engines/adaptive.ts
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import {
  type AdaptiveFitInput,
  type AdaptiveGoal,
  fitAdaptiveModel,
  predictWeeklyRate,
  recommend,
  requiredIntake,
} from "../src/engines/adaptive";
import { phases, simulate } from "./simulate";

const here = dirname(fileURLToPath(import.meta.url));
const JSON_PATH = resolve(here, "fixtures/adaptive-fixture.json");
const SWIFT_PATH = resolve(here, "../../MyCoachTests/AdaptiveModelFixture.swift");

interface Case {
  name: string;
  input: AdaptiveFitInput;
  goal: AdaptiveGoal;
  desiredWeightKg: number;
  plan: { trainingKcal: number; restKcal: number; trainingDaysPerWeek: number };
}

function cases(): Case[] {
  const truth = { maintenance: 2650, perThousandSteps: 38, adaptation: 120, referenceIntake: 2300 };
  const a = simulate({ seed: 101, startWeightKg: 88, truth, intakePlan: phases([35, 2300], [35, 2000], [21, 2150]), stepsMean: 8200 });
  const b = simulate({ seed: 202, startWeightKg: 70, truth: { ...truth, maintenance: 2400 }, intakePlan: phases([42, 2600]), stepsMean: 6000, pMissingIntake: 0.35 });
  const c = simulate({ seed: 303, startWeightKg: 95, truth, intakePlan: phases([12, 2100]), stepsMean: 9000 });
  return [
    {
      name: "cut-13-weeks",
      input: { days: a.days, priorMaintenanceKcal: 2350, bodyWeightKg: 86, fallbackSteps: 8000, fallbackIntakeKcal: 2100 },
      goal: "cut",
      desiredWeightKg: 80,
      plan: { trainingKcal: 2300, restKcal: 1800, trainingDaysPerWeek: 4 },
    },
    {
      name: "gain-sparse-logging",
      input: { days: b.days, priorMaintenanceKcal: 2250, bodyWeightKg: 71, fallbackSteps: 7000, fallbackIntakeKcal: 2500 },
      goal: "gain",
      desiredWeightKg: 76,
      plan: { trainingKcal: 2700, restKcal: 2200, trainingDaysPerWeek: 5 },
    },
    {
      name: "new-user-12-days",
      input: { days: c.days, priorMaintenanceKcal: 2500, bodyWeightKg: 95, fallbackSteps: 8000, fallbackIntakeKcal: 2100 },
      goal: "cut",
      desiredWeightKg: 85,
      plan: { trainingKcal: 2300, restKcal: 1800, trainingDaysPerWeek: 3 },
    },
    {
      name: "no-weights",
      input: { days: [{ intakeKcal: 2000 }, { intakeKcal: 2100, steps: 9000 }], priorMaintenanceKcal: 2400, bodyWeightKg: 80, fallbackSteps: 8000, fallbackIntakeKcal: 2000 },
      goal: "maintenance",
      desiredWeightKg: 80,
      plan: { trainingKcal: 2400, restKcal: 1900, trainingDaysPerWeek: 4 },
    },
  ];
}

function expected(c: Case) {
  const m = fitAdaptiveModel(c.input);
  const rec = recommend(m, c.plan, c.goal, c.desiredWeightKg, m.currentSteps);
  return {
    observations: m.observations,
    loggedIntakeDays: m.loggedIntakeDays,
    weighIns: m.weighIns,
    theta: m.theta,
    covariance: m.covariance,
    maintenanceKcal: m.maintenanceKcal,
    maintenanceSD: m.maintenanceSD,
    currentSteps: m.currentSteps,
    currentIntakeKcal: m.currentIntakeKcal,
    confidence: m.confidence,
    rmseKcal: m.rmseKcal ?? null,
    trendLevelKg: m.trend?.levelKg ?? null,
    trendSlopeKgPerWeek: m.trend?.slopeKgPerWeek ?? null,
    trendSlopeSDKgPerWeek: m.trend?.slopeSDKgPerWeek ?? null,
    predictAt2000: predictWeeklyRate(m, 2000, 8000),
    requiredForMinusHalf: requiredIntake(m, -0.5, 9000),
    recommendation: {
      targetKgPerWeek: rec.targetKgPerWeek,
      deltaKcal: rec.deltaKcal,
      shouldAdjust: rec.shouldAdjust,
      requiredAverageIntake: rec.requiredAverageIntake,
    },
  };
}

function build() {
  return {
    note: "Generated by web/tests/adaptiveFixture.test.ts (npm run fixtures). Do not edit by hand.",
    cases: cases().map((c) => ({
      name: c.name,
      input: {
        days: c.input.days.map((d) => ({ weightKg: d.weightKg ?? null, intakeKcal: d.intakeKcal ?? null, steps: d.steps ?? null })),
        priorMaintenanceKcal: c.input.priorMaintenanceKcal,
        bodyWeightKg: c.input.bodyWeightKg,
        fallbackSteps: c.input.fallbackSteps,
        fallbackIntakeKcal: c.input.fallbackIntakeKcal,
      },
      goal: c.goal,
      desiredWeightKg: c.desiredWeightKg,
      plan: c.plan,
      expected: expected(c),
    })),
  };
}

describe("adaptive model parity fixture", () => {
  it(process.env.GEN_FIXTURE ? "regenerates the fixture" : "matches the committed fixture", () => {
    const fixture = build();
    const json = JSON.stringify(fixture);
    if (process.env.GEN_FIXTURE) {
      if (!existsSync(dirname(JSON_PATH))) mkdirSync(dirname(JSON_PATH), { recursive: true });
      writeFileSync(JSON_PATH, JSON.stringify(fixture, null, 1) + "\n");
      writeFileSync(
        SWIFT_PATH,
        `// Generated by web/tests/adaptiveFixture.test.ts (npm run fixtures). Do not edit by hand.\n` +
          `// Expected outputs come from the TypeScript reference model; AdaptiveModelTests checks the Swift port matches.\n\n` +
          `enum AdaptiveModelFixture {\n    static let json = #"""\n${json}\n"""#\n}\n`,
      );
      return;
    }
    const committed = JSON.parse(readFileSync(JSON_PATH, "utf-8"));
    expect(committed).toEqual(JSON.parse(json));
  });
});
